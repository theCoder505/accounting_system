<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use App\Models\Contactus;
use Illuminate\Http\Request;

class ContactusController extends Controller
{
    /**
     * Display a listing of the resource.
     *
     * @return \Illuminate\Http\Response
     */
    public function index()
    {
        $datas = Contactus::orderBy('id', 'desc')->where('status', 1)->get();
        return view('admin.contactus.index',compact('datas'));
    }

    public function pending_contact_us()
    {
        $datas = Contactus::orderBy('id', 'desc')->where('status', 0)->get();
        return view('admin.contactus.pending_contact_us',compact('datas'));
    }

    /**
     * Show the form for creating a new resource.
